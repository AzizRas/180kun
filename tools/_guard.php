<?php
declare(strict_types=1);

/**
 * Защита инструментов от запуска из браузера.
 *
 * Файлы в tools/ закрыты через .htaccess, но Apache есть не везде:
 * на Railway, Render, Fly и за nginx правила .htaccess игнорируются,
 * и папка оказывается открытой всему интернету. Для smoke.php это
 * означало бы, что любой желающий может переписать modules.php,
 * стереть базу и создать тестовых пользователей на боевом сайте.
 *
 * Проверка на уровне PHP работает на любом сервере, поэтому она здесь
 * и является основной, а .htaccess — вторым рубежом.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    header('Content-Type: text/plain; charset=utf-8');
    exit("Этот инструмент запускается только из командной строки.\n");
}
